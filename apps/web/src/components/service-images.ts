function slugify(text: string) {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/--+/g, "-")
    .trim();
}

export function getServiceImage(service: {
  slug?: string;
  name?: string;
  category?: string;
  imageUrl?: string | null;
}): string {
  if (service.imageUrl && service.imageUrl.startsWith("http")) {
    return service.imageUrl;
  }

  if (service.slug) {
    const fromSlug = serviceImagesBySlug[service.slug];
    if (fromSlug) return fromSlug;
  }

  if (service.name) {
    const slug = slugify(service.name);
    const fromName = serviceImagesBySlug[slug];
    if (fromName) return fromName;
  }

  if (service.category) {
    const fromCategory = categoryDefaultImages[service.category];
    if (fromCategory) return fromCategory;
  }

  return "https://images.unsplash.com/photo-1621905251189-08b45d6a269e?w=600&q=80&fit=crop";
}
